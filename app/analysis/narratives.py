def select_narrative(
    scenario_id: int,
    pattern_index: int,
) -> str:
    """Return the locked Persian narrative for a scenario/pattern.

    Consumes the scenario_id produced by Unit 7.3 and the user-selected
    pattern_index. No creative rewriting is performed.
    """
    if not isinstance(scenario_id, int):
        raise TypeError("scenario_id must be an int.")
    if not isinstance(pattern_index, int):
        raise TypeError("pattern_index must be an int.")

    if scenario_id < 1 or scenario_id > 9:
        raise ValueError(
            f"scenario_id must be 1-9, got {scenario_id}."
        )

    if pattern_index not in (1, 2, 3):
        raise ValueError(
            "pattern_index must be 1, 2, or 3."
        )

    patterns = NARRATIVES.get(scenario_id)
    if not patterns or len(patterns) != 3:
        raise ValueError(
            f"Scenario {scenario_id} does not have 3 locked patterns."
        )

    return patterns[pattern_index - 1]


def narratives_self_tests() -> Dict[str, Any]:
    """Deterministic self-test for the locked narrative library."""
    tests: Dict[str, Any] = {}

    tests["narrative_count"] = len(NARRATIVES) == 9
    tests["patterns_per_scenario"] = all(
        len(v) == 3 for v in NARRATIVES.values()
    )
    tests["total_patterns"] = sum(
        len(v) for v in NARRATIVES.values()
    ) == 27

    for scenario_id in range(1, 10):
        for pattern_index in (1, 2, 3):
            text = select_narrative(scenario_id, pattern_index)
            tests[
                f"scenario_{scenario_id}_pattern_{pattern_index}"
            ] = (
                isinstance(text, str)
                and len(text) > 0
            )

    try:
        select_narrative(0, 1)
        tests["invalid_scenario_rejected"] = False
    except ValueError:
        tests["invalid_scenario_rejected"] = True

    try:
        select_narrative(1, 4)
        tests["invalid_pattern_rejected"] = False
    except ValueError:
        tests["invalid_pattern_rejected"] = True

    try:
        select_narrative(1, "1")
        tests["invalid_pattern_type_rejected"] = False
    except TypeError:
        tests["invalid_pattern_type_rejected"] = True

    try:
        select_narrative("1", 1)
        tests["invalid_scenario_type_rejected"] = False
    except TypeError:
        tests["invalid_scenario_type_rejected"] = True

    tests["narrative_unchanged"] = (
        select_narrative(1, 1)
        == NARRATIVES[1][0]
    )

    return {
        "status": "PASS" if all(tests.values()) else "FAIL",
        "passed": sum(tests.values()),
        "total": len(tests),
        "tests": tests,
    }
