def get_narrative(scenario_id: int, pattern_index: int = 1) -> Dict[str, str]:
    """Return the locked narrative for a scenario and pattern.

    Args:
        scenario_id: 1–9
        pattern_index: 1, 2, or 3 (1-based)

    Returns:
        Dict with keys: pattern, title, text

    Raises:
        ValueError: if scenario_id or pattern_index is out of range.
    """
    if scenario_id not in NARRATIVES:
        raise ValueError(f"Unknown scenario_id: {scenario_id}")
    if pattern_index not in (1, 2, 3):
        raise ValueError("pattern_index must be 1, 2, or 3.")

    return dict(NARRATIVES[scenario_id][pattern_index - 1])


def validate_narratives() -> Dict[str, Any]:
    """Validate the locked narrative library structure."""
    total_patterns = 0
    for scenario_id in range(1, 10):
        patterns = NARRATIVES[scenario_id]
        assert len(patterns) == 3, f"Scenario {scenario_id} must have 3 patterns"
        for pattern in patterns:
            assert "pattern" in pattern
            assert "title" in pattern
            assert "text" in pattern
            assert isinstance(pattern["text"], str)
            assert len(pattern["text"].strip()) > 0
            total_patterns += 1

    return {
        "scenarios": 9,
        "patterns": total_patterns,
        "status": "LOCKED",
    }


NARRATIVE_VALIDATION = validate_narratives()
assert NARRATIVE_VALIDATION["patterns"] == 27